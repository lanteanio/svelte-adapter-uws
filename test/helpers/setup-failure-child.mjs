import assert from 'node:assert/strict';
import { once } from 'node:events';
import { WebSocket } from 'ws';
import { startRealRuntime, connectRealClient } from './real-runtime.js';
import { setOperationalEventSink } from '../../src/runtime/diagnostic.js';
import { formatDiagnostic } from '../../src/runtime/diagnostic-format.js';
import { ADAPTER_ERROR_REGISTRY } from '../../src/runtime/error-registry.js';
const mode = process.argv[2];
const records = [];
const dispose = setOperationalEventSink(record => records.push(record));
const server = await startRealRuntime({ variant: 'setupfailure' });
let healthy;
try {
	const warmup = await connectRealClient(server.wsUrl);
	assert.deepEqual((await warmup.waitFor(frame => frame?.topic === 'probe')).parsed.data, { opens: 1, closes: 0, connections: 1 });
	const warmupClosed = once(warmup.ws, 'close');
	warmup.ws.close();
	await warmupClosed;
	const failing = new WebSocket(server.wsUrl, { headers: { 'x-setup-failure': mode, 'x-request-id': 'setup-probe' } });
	let accepted = false;
	failing.once('open', () => { accepted = true; });
	const [code] = await once(failing, 'close');
	assert.equal(accepted, true, 'failure happened after the 101 handshake');
	assert.equal(code, 1011, 'failed setup closes only its accepted connection');
	healthy = await connectRealClient(server.wsUrl);
	assert.deepEqual((await healthy.waitFor(frame => frame?.topic === 'probe')).parsed.data, { opens: 2, closes: 1, connections: 1 });
	const events = records.filter(record => record.event === 'runtime.websocket-open.failed');
	assert.equal(events.length, 1);
	const event = events[0];
	assert.equal(event.component, 'runtime.websocket-open');
	assert.equal(event.severity, 'error');
	assert.equal(event.message, 'Connection setup failed after the upgrade completed.');
	assert.equal(event.attributes.requestId, 'setup-probe');
	assert.match(event.attributes.error.message, /fixture (platform allocation|connection registration) failed/);
	const entry = ADAPTER_ERROR_REGISTRY.find(item => item.id === 'ADAPTER-ERR-CONNECTION-SETUP');
	assert.ok(entry, 'shared setup identity exists');
	assert.ok(formatDiagnostic(event).startsWith(entry.messagePrefix));
	assert.equal(records.some(record => record.event === 'ws.hook.open.failed' || record.event === 'ws.hook.close.failed'), false);
	console.log('CONNECTION_SETUP_RECOVERED');
} finally { healthy?.close(); await server.stop(); dispose(); }
